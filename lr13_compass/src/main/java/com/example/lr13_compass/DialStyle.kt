package com.example.lr13_compass

// Стили отрисовки циферблата компаса.
enum class DialStyle {
    CLASSIC,    // Традиционный компас с делениями каждые 10° и N/S/E/W
    AVIATION,   // Авиационный стиль: тёмный фон, крупные деления каждые 30°
    MINIMAL     // Минимализм: только стрелка и 4 основных направления
}